export function summarizeHealth(records) {
  let totalCount = 0
  let totalCal = 0
  let totalHeart = 0
  let heartDays = 0
  for (const d of records) {
    totalCount += d.count
    totalCal += d.cal
    if (d.count) {
      totalHeart += d.heart
      heartDays++
    }
  }
  return {
    totalCount,
    totalCal,
    avgHeart: heartDays ? Math.round(totalHeart / heartDays) : 0,
  }
}

